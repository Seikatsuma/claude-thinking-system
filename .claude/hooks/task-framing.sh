#!/usr/bin/env bash
# UserPromptSubmit — понять задачу пользователя с первого раза.
# Сам ничего не решает и никого не вызывает: подкладывает в разбор то, что нужно именно
# для этого сообщения. Думает основная модель — на понимании задачи не экономим.
# 12.09.26 — разбор первым блоком, без подтверждений.
# 13.09.26 — по разбору чата claudecodeui (5–12.09): граница «делать сам / один вопрос»,
#   сигналы по словам пользователя (не изменилось, тормозит, давление, статус), словарь его слов.
#   Правила — ~/CLAUDE.md «Протокол исполнения задачи»; словарь — ~/.claude/workspace/WORDS.md.
set +e
HOOK_IN="$(cat 2>/dev/null)" python3 - <<'PY' 2>/dev/null
import os, json, sys, re

try:
    d = json.loads(os.environ.get("HOOK_IN") or "{}")
except Exception:
    sys.exit(0)
prompt = (d.get("prompt") or "").strip()
sess = d.get("session_id") or ""
if not prompt or prompt.startswith("/"):
    sys.exit(0)
# 14.09.26: служебные сообщения (уведомления фоновых задач, отзывы Stop-хуков, напоминания системы)
# приходят сюда как «сообщение пользователя» — подсказка ложно видела в них «опять», «ключ», «тормозит».
# «<system» — начало любого системного тега (<system-reminder>, <system-notification>…): пользователь пишет голосом
# и такие теги сам не набирает. «This session is being continued» — пересказ чата после сжатия контекста,
# «Another Claude session sent a message» — письмо из соседнего чата: оба не сообщения пользователя.
SERVICE_MARKERS = ("<task-notification", "<task-id>", "<system", "Stop hook feedback",
                   "Stop hook blocking error", "[SYSTEM NOTIFICATION", "[MESSAGE FROM NON-USER",
                   "This session is being continued", "Another Claude session sent a message",
                   "<command-", "<local-command", "[Your previous response", "Base directory for this skill",
                   "[Request interrupted", "Continue from where you left off")
head = prompt[:500]
if any(mk in head for mk in SERVICE_MARKERS) or (prompt.startswith("{") and '"type"' in head):
    sys.exit(0)
low = prompt.lower().replace("ё", "е")


def emit(parts):
    if parts:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "UserPromptSubmit",
                                                 "additionalContext": "\n\n".join(parts)}},
                         ensure_ascii=False))
    sys.exit(0)


SMALL_TALK = r"^(?:да|нет|ок|окей|ага|угу|хорошо|спасибо|понял|ясно|дальше|продолжай|давай дальше|стоп|го|делай|давай)[\s.!,)]*$"
STATUS = (r"^(?:ну|жду|а|хай|привет|ау|алло|ты тут|ты здесь|как там|что там|готово|скоро|долго еще|"
          r"продолжаешь|продолжишь|продолжишь запрос|ты продолжаешь|ответишь)[\s.!?,)]*$")
if re.match(SMALL_TALK, low):
    sys.exit(0)

parts = []
# 14.09.26: маркеры — целыми словами. Подстрокой «снова» ловилось внутри «оснОВАННЫЙ», «обоснованно»
# (голосовые пользователя) — ложная «повторная поправка». Начала слова мало: «снова» в «основанный» не с начала.
B = r"(?<![а-яa-z])"  # до маркера не буква (low уже в нижнем регистре, ё -> е)
A = r"(?![а-яa-z])"   # после маркера не буква
REPEAT = re.compile(B + r"(?:я же (?:тебе )?(?:говорил|просил|писал)|уже (?:просил|говорил|писал|исправлял)|"
                    r"опять|снова|сколько раз|в который раз|по новой|то же самое|каждый раз повторять|"
                    r"уже была такая)" + A)
if REPEAT.search(low):
    parts.append("ЕСЛИ ЭТО ПОВТОРНАЯ ПОПРАВКА (пользователь жалуется, что уже говорил или что проблема вернулась; "
                 "«опять / снова» в описании работы — не жалоба): помимо задачи в ЭТОЙ ЖЕ сессии правка "
                 "уходит в среду (хук / CLAUDE.md / словарь WORDS.md) + learning-loop record-trace. "
                 "Объяснять дважды нельзя.")

if re.match(STATUS, low):
    parts.append("СТАТУС. Пользователь ждёт и не видит движения. Ответ в три строки: готово или нет; если "
                 "нет — что сейчас идёт и когда закончится; нужно ли что-то от пользователя. Без устройства "
                 "и причин. Если работа оборвалась — так и сказать и продолжить.")
    emit(parts)

SIGNALS = (
    (r"не измени|не поменя|та же ошибка|так и не" + A + r"|пока не вижу|ничего не измен|не починил|"
     r"исправлени[яй] нет|не исправил|" + B + r"(?:опять|снова)" + A + r"|все так же|до сих пор",
     "СИГНАЛ «НЕ ИЗМЕНИЛОСЬ» — если пользователь жалуется, что правка не видна или проблема осталась. Пользователь смотрит на iPhone, в приложение с экрана «Домой». Сначала "
     "проверь, доехала ли правка до ЕГО устройства (кэш, служебный работник, неделями живущая "
     "сессия приложения), и не та ли это уже известная причина. Не чини заново и не пересказывай "
     "причину ещё раз; «исправлено» — только после проверки с его стороны."),
    (r"фриз|зависа|завис|тормоз|долго груз|белый экран|не груз|подвиса|медленн|лага",
     "СИГНАЛ «ТОРМОЗИТ / ЗАВИСАЕТ». Первое действие — замер: время ответа сервера на запросы "
     "страницы и что видит браузер. Только потом код. 6–11.09 фриз три дня лечили прокруткой, а "
     "причина была в запросе на 141 секунду."),
    (r"у (?:тебя|етбя|тя) (?:же )?(?:есть|уже)|ты же (?:можешь|должен|знаешь)|ты же сам|"
     r"найди (?:его |ее |её )?(?:и )?сам|сам (?:найди|подвяжи|разберись)|точно есть|он же есть|"
     r"посмотри в env|доступ (?:же )?есть|псть домтуп",
     "СИГНАЛ «ДАВЛЕНИЕ». Настойчивость пользователя — не доказательство. Проверь делом; если проверка "
     "говорит обратное — скажи прямо и спокойно, что проверил и что нашлось. Не понижай проверку "
     "и не меняй проверенный вывод, чтобы дать желаемый ответ (12.09: под «найди сам» скопирован "
     "мёртвый ключ — вход упал, пользователь 5 часов без ответа)."),
)
fired = [text for pat, text in SIGNALS if re.search(pat, low)]

REQUEST = (r"(?:поправ|исправ|сделай|сделать|добав|убер|удал|поменя|измен|провер|внедр|"
           r"настрой|запусти|обнов|перенес|напиш|собер|отправ|переделай|дораб|верни|"
           r"найди|найти|постав|установи|подключ|подвяж|разбер|посмотри|проанализ|выпиши|пришли|скачай|"
           r"надо|нужн|чтоб|хочу|хотел|должн|пусть|давай|"
           r"не работа|не открыва|не видн|не грузит|не появ|съезжа|слома|криво|кривая|"
           r"сломан|ошибк|пропал|исчез|налеза|обрез)")
is_request = bool(re.search(REQUEST, low))
is_status_question = low.endswith("?") and len(prompt) < 60 and not is_request and not fired
substantive = not is_status_question and (len(prompt) >= 60 or is_request or bool(fired))

if substantive:
    parts.insert(0,
        "ПРОТОКОЛ ИСПОЛНЕНИЯ (сессия %s):\n"
        "1. ПОНЯТЬ. Первым блоком ответа — «Как я понял задачу»: сообщение пользователя чистым текстом "
        "(голос: убери оговорки и ошибки распознавания, сохрани КАЖДОЕ требование, ничего своего). "
        "Затем: цель — что пользователь увидит у себя, когда готово; объект — какой именно экран, файл, "
        "аккаунт или чат и по чему ты это определил; объём — что меняешь и что остаётся как было. "
        "«Убери X у картинки» = остальное не трогать; перед правкой готового артефакта — посмотри, "
        "кто и по чьему заказу его сделал.\n"
        "2. ДЕЛАЙ САМ И БЕЗ ОСТАНОВОК (пользователь 15.09.26: «я не могу постоянно быть на связи и подтверждать»). "
        "Вопросов и подтверждений не жди. Слово или объект допускают 2+ толкования — выбери самое вероятное по "
        "контексту (проект чата, прошлые сообщения, файлы), назови его одной строкой в разборе и делай. "
        "Техническое «как», порядок работ, план на утверждение — никогда не вопрос. Шаг необратимый (удаление), "
        "чужой (соседний бот, чужой аккаунт, отправка людям) или про деньги — не делай ИМЕННО его, доделай всё "
        "остальное, а в конце ответа блок «Ждёт вашего да»: что и зачем, одной строкой на шаг. Проблема названа "
        "конкретно (фриз, прыгает, обрезается) — начинай с замера.\n"
        "3. ПРОВЕРКА — на экране пользователя, а не в файлах; grep, код возврата, коммит, статус сервиса — не доказательство. "
        "Существенный результат (код, правила ИИ, документ людям, деньги/прод) — ОДИН проверяющий-помощник на Sonnet "
        "(critic-* по области или verifier): задание = исходный текст пользователя + что сделано, без переписки; проверяет ДЕЛОМ (файлы, команда, снимок); "
        "замечания исправь сам; остались КРИТИЧНО/СЕРЬЁЗНО — ещё круг с журналом, потолок 3. Не звать: круги больше трёх, несколько критиков, "
        "слепые прогоны. Пропускать проверку ради экономии нельзя (пользователь 15.09: переделки дороже).\n"
        "4. ТОТ ЖЕ СПОСОБ провалился дважды по одной причине — меняй способ, а не параметры.\n"
        "5. САМ СЕБЕ ОТВЕЧАЙ. Перед концом ответа в своём размышлении перечитай последнюю строку: если там вопрос пользователю "
        "(«сделать?», «делаю сейчас или ждёте?», «окей?», «какой вариант?») или обещание «сейчас сделаю» — задай этот вопрос "
        "себе, ответь самым полезным вариантом по контексту и продолжай работу в этом же ответе. Вопрос пользователю остаётся "
        "только про удаление, чужое и деньги — блоком «Ждёт вашего да» в конце. Сообщений «продолжай» Пользователю не шлёт никто — "
        "это решаешь ты сам.\n"
        "6. В конце ответа — «Поправки»: 1–3 пункта из своего размышления (где мог ошибиться, какое толкование "
        "выбрал). Это сведения для пользователя, НЕ вопрос и не повод остановиться; нечего — не пиши. Поиск в интернете — "
        "всегда, но дёшево: WebSearch 3–6 запросов → 3–5 источников через WebFetch с вопросом."
        % sess)
parts.extend(fired)

# 14.09.26 — «сначала найди готовое».
FIND_CWD = d.get("cwd") or ""
FIND_SKIP = re.compile(r"^/tmp(?:/|$)")  # 15.09.26: и в каталогах проектов (пользователь: «всегда ищи»); /tmp — автоматика
FIND_TOOLS = (r"nginx|systemd|docker|pwa|ios\b|iphone|айфон|android|telegram|телеграм|\bapi\b|\bапи\b|github|гитхаб|"
              r"postgres|redis|cloudflare|yougile|adesk|amo ?crm|miro|notion|google|webhook|oauth|python|node|"
              r"библиотек|фреймворк|плагин|claude code|tmux|тмукс|termius|термиус|vs ?code|вс ?код|happy|хеппи")
FIND_NOUN = r"(?:\S*-)?(?:бот|приложени|сайт|сервис|модул|парсер|интеграц|проект|виджет|расширени|систем\w* учета)"
FIND_SKIPPREP = r"(?!(?:в|во|на|у|к|ко|из|с|со|от|про|для|по|о|об)\s)"
FIND = (
    # новый проект, бот, модуль — сначала готовые аналоги («Поставь телеграм-бот напоминаний»)
    r"(?:сдела|созда|напиш|собер|разраб|запили|подними|нуж|хочу|нов|найди|найти|постав|установ|скача)\w*\s+"
    r"(?:%s\S+\s+){0,3}?%s(?!\w*\s+на (?:паузу|стоп))" % (FIND_SKIPPREP, FIND_NOUN),
    # готовое, GitHub, аналоги, выбор готового решения
    r"готов(?:ое|ый|ая|ые|ую|ого|ых)\s+(?:\S+\s+){0,2}?(?:\S*-)?(?:решени|вариант|шаблон|бот|приложени|проект|"
    r"модул|библиотек|скрипт|сервис|инструмент|продукт|систем|реализац|парсер)|"
    r"(?:найди|найти|поищи|поиск|ищи|искать|скача|возьми|посмотри|похож)\w*.{0,60}(?:гитхаб|github)|"
    r"(?:гитхаб|github)\w*.{0,40}(?:найди|поищи|похож|аналог|готов)|"
    r"есть (?:ли )?(?:\S+\s+){0,2}?(?:готов|аналог|продукт|приложени|сервис|библиотек|инструмент|программ)|"
    r"аналог|похож\w+ (?:проект|решени|бот|приложени|сервис)|какую библиотек|библиотек\w* для|"
    r"как(?:ой|ую|ие) (?:сервис|инструмент|фреймворк|программ)|какую (?:взять|выбрать)|что лучше|что выбрать|"
    r"шаблон|равнять|сравни с тем,? \S+ \S*(?:делают|едлают|у других)|в сравнении с|лучшие практики|"
    r"(?:поиск|подбор|подбери|подобрать)\w*\s+(?:\S+\s+){0,2}?подходящ",
    # экспертная область
    r"(?:^|[^а-я])(?:учет|бухгалт|налог|усн|ндс|ндфл|ддс|финансов|отчетност|юрид|закон|договор|оферт|трудов|"
    r"методик|кандидат|отклик|найм|для детей|детск\w+ (?:приложени|интерфейс|дизайн))",
    # настройка и поведение чужого инструмента
    r"(?:настро|подключ|интегрир|лимит|ограничени|по умолчанию|не подхватыва|перезапус\w* при|выгрузк|"
    r"не обновля|загрузк|сочетани\w* клавиш|горяч\w+ клавиш|связан\w* ли)\w*.{0,80}(?:%s)|(?:%s).{0,80}(?:настро|подключ|лимит|"
    r"ограничени|по умолчанию|не подхватыва|перезапус|выгрузк|не обновля|загрузк|связан\w* ли)" % (FIND_TOOLS, FIND_TOOLS),
    # цены и товары
    r"сколько стоит|(?:^|[^а-я])цен[аыуе]?(?:[^а-я]|$)|купить|в наличии|есть ли .{0,50} в (?:dns|днс|мвидео|"
    r"ситилинк)|wildberries|вайлдберриз|валдберис|(?:^|[^a-z])wb(?:[^a-z]|$)|(?:^|[^а-я])вб(?:[^а-я]|$)|ozon|озон|"
    r"маркетплейс|яндекс маркет|авито|сочетани\w* клавиш",
    # новые правила для самих ИИ
    r"правил\w* для (?:ии|claude|клод|чат|модел)|нов\w+ (?:хук|правил)|промпт",
)
FIND_HINT = ("ИЩИ ГОТОВОЕ до создания (пользователь 15.09: найденное окупается): своё (grep, темы) → WebSearch 3–6 "
             "запросов (разные формулировки, и по-английски) → 3–5 лучших источников через WebFetch с конкретным вопросом → взять лучшее, в ответе — откуда. "
             "Экономно: без помощников и копий чата для поиска, без страниц целиком; "
             "проверка цитат — только деньги, право, налоги. Ошибки своего кода и данные сервера — мерить, не искать.")
if not FIND_SKIP.search(FIND_CWD) and (substantive or any(re.search(p, low) for p in FIND)):  # 15.09: всегда на содержательную задачу
    parts.append(FIND_HINT)

if substantive or fired:
    words = []
    try:
        for line in open(os.path.expanduser("~/.claude/workspace/WORDS.md"), encoding="utf-8"):
            if line.startswith("## Без хука"):
                break
            m = re.match(r"^- \*\*(.+?)\*\* — (.+)$", line.rstrip("\n"))
            if not m:
                continue
            keys = [k.strip().lower().replace("ё", "е") for k in m.group(1).split("|") if k.strip()]
            if any(re.search(r"(?:^|[^а-яa-z])" + re.escape(k), low) for k in keys):
                words.append("• %s — %s" % (keys[0], m.group(2)))
    except Exception:
        pass
    if words:
        parts.append("СЛОВА ПОЛЬЗОВАТЕЛЯ в этом сообщении (~/.claude/workspace/WORDS.md):\n" + "\n".join(words[:4]))

emit(parts)
PY
exit 0
