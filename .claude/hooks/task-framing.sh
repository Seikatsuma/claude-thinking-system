#!/usr/bin/env bash
# UserPromptSubmit — понять задачу с первого раза.
# Сам ничего не решает и никого не вызывает: подкладывает в разбор то, что нужно именно
# для этого сообщения. Думает основная модель — на понимании задачи не экономим.
# Правила — ~/CLAUDE.md; словарь слов пользователя — ~/.claude/workspace/WORDS.md.
set +e
HOOK_IN="$(cat 2>/dev/null)" python3 - <<'PY' 2>/dev/null
import os, json, sys, re

try:
    d = json.loads(os.environ.get("HOOK_IN") or "{}")
except Exception:
    sys.exit(0)
prompt = (d.get("prompt") or "").strip()
if not prompt or prompt.startswith("/"):
    sys.exit(0)
# Служебные сообщения (уведомления фоновых задач, отзывы хуков, пересказ после сжатия контекста)
# приходят сюда как «сообщение пользователя» — их не разбираем.
SERVICE_MARKERS = ("<task-notification", "<system", "Stop hook feedback", "[SYSTEM NOTIFICATION",
                   "This session is being continued", "<command-", "<local-command",
                   "[Request interrupted", "Continue from where you left off")
head = prompt[:500]
if any(mk in head for mk in SERVICE_MARKERS):
    sys.exit(0)
low = prompt.lower().replace("ё", "е")


def emit(parts):
    if parts:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "UserPromptSubmit",
                                                 "additionalContext": "\n\n".join(parts)}},
                         ensure_ascii=False))
    sys.exit(0)


SMALL_TALK = r"^(?:да|нет|ок|окей|ага|хорошо|спасибо|понял|ясно|дальше|продолжай|стоп|делай|давай)[\s.!,)]*$"
STATUS = r"^(?:ну|а|ау|ты тут|ты здесь|как там|что там|готово|скоро|долго еще|продолжаешь)[\s.!?,)]*$"
if re.match(SMALL_TALK, low):
    sys.exit(0)

B = r"(?<![а-яa-z])"  # маркеры — целыми словами: «снова» не должно ловиться внутри «основанный»
A = r"(?![а-яa-z])"
parts = []

REPEAT = re.compile(B + r"(?:я же (?:тебе )?(?:говорил|просил|писал)|уже (?:просил|говорил|писал)|"
                    r"опять|снова|сколько раз|в который раз|то же самое)" + A)
if REPEAT.search(low):
    parts.append("ЕСЛИ ЭТО ПОВТОРНАЯ ПОПРАВКА (пользователь жалуется, что уже говорил или проблема вернулась): "
                 "помимо задачи в ЭТОЙ ЖЕ сессии правка уходит в среду — правило CLAUDE.md, хук или словарь "
                 "WORDS.md — и урок в память. Объяснять дважды нельзя.")

if re.match(STATUS, low):
    parts.append("СТАТУС. Пользователь ждёт и не видит движения. Ответ в три строки: готово или нет; если нет — "
                 "что сейчас идёт и когда закончится; нужно ли что-то от пользователя. Работа оборвалась — "
                 "так и сказать и продолжить.")
    emit(parts)

SIGNALS = (
    (r"не измени|не поменя|та же ошибка|пока не вижу|ничего не измен|не починил|не исправил|все так же|до сих пор",
     "СИГНАЛ «НЕ ИЗМЕНИЛОСЬ». Сначала проверь, дошла ли правка туда, где пользователь смотрит (кэш, старая "
     "версия, не тот экран или адрес), и не та ли это уже известная причина. Не чини заново вслепую; "
     "«исправлено» — только после проверки с его стороны."),
    (r"фриз|зависа|завис|тормоз|долго груз|белый экран|не груз|подвиса|медленн|лага",
     "СИГНАЛ «ТОРМОЗИТ / ЗАВИСАЕТ». Первое действие — замер (время ответа, что видит клиент), только потом код."),
    (r"у (?:тебя|тя) (?:же )?(?:есть|уже)|ты же (?:можешь|должен|знаешь)|найди (?:и )?сам|сам (?:найди|разберись)|"
     r"точно есть|доступ (?:же )?есть",
     "СИГНАЛ «ДАВЛЕНИЕ». Настойчивость — не доказательство. Проверь делом; если проверка говорит обратное — "
     "скажи прямо и спокойно, что проверил и что нашлось. Проверенный вывод под давлением не меняй."),
)
fired = [text for pat, text in SIGNALS if re.search(pat, low)]

REQUEST = (r"(?:поправ|исправ|сделай|сделать|добав|убер|удал|поменя|измен|провер|внедр|настрой|запусти|обнов|"
           r"напиш|собер|отправ|переделай|верни|найди|найти|постав|установи|подключ|разбер|посмотри|"
           r"проанализ|надо|нужн|чтоб|хочу|должн|пусть|давай|не работа|не открыва|слома|ошибк|пропал|обрез)")
is_request = bool(re.search(REQUEST, low))
is_status_question = low.endswith("?") and len(prompt) < 60 and not is_request and not fired
substantive = not is_status_question and (len(prompt) >= 60 or is_request or bool(fired))

if substantive:
    parts.insert(0,
        "ПРОТОКОЛ ИСПОЛНЕНИЯ:\n"
        "1. ПОНЯТЬ. Первым блоком ответа — «Как я понял задачу»: сообщение пользователя чистым текстом (убери "
        "оговорки и ошибки распознавания, сохрани КАЖДОЕ требование, ничего своего). Затем: цель — что "
        "пользователь увидит, когда готово; объект — какой именно экран, файл, аккаунт и по чему определён; "
        "объём — что меняешь и что остаётся как было.\n"
        "2. ДЕЛАЙ САМ И БЕЗ ОСТАНОВОК. Двусмысленность — выбери самое вероятное толкование по контексту, назови "
        "строкой и делай. Техническое «как» и план — не вопрос. Необратимое, чужое или деньги — не делай ИМЕННО "
        "этот шаг, доделай остальное, в конце блок «Ждёт вашего да». Проблема названа конкретно — начни с замера.\n"
        "3. ПРОВЕРКА — на конечном результате, а не в файлах; код возврата, коммит, статус — не доказательство. "
        "Существенный результат — ОДИН независимый проверяющий: задание = исходный текст пользователя + что "
        "сделано; проверяет делом; потолок 3 круга.\n"
        "4. ТОТ ЖЕ СПОСОБ провалился дважды по одной причине — меняй способ, а не параметры.\n"
        "5. САМ СЕБЕ ОТВЕЧАЙ. Перед концом ответа перечитай последнюю строку: вопрос пользователю или обещание — "
        "задай его себе, ответь самым полезным вариантом и продолжай работу.\n"
        "6. В конце ответа — «Поправки»: 1–3 пункта (где мог ошибиться, какое толкование выбрал). Сведения, "
        "не вопрос.")
    parts.append("ИЩИ ГОТОВОЕ до создания нового: своё (поиск по проекту, память) → веб-поиск 3–6 запросов "
                 "(разные формулировки, и по-английски) → 3–5 лучших источников с конкретным вопросом → "
                 "взять лучшее, в ответе — откуда. Ошибки своего кода и данные — мерить, а не искать.")
parts.extend(fired)

if substantive or fired:
    words = []
    try:
        for line in open(os.path.expanduser("~/.claude/workspace/WORDS.md"), encoding="utf-8"):
            if line.startswith("## Без хука"):
                break
            m = re.match(r"^- \*\*(.+?)\*\* — (.+)$", line.rstrip("\n"))
            if not m:
                continue
            keys = [k.strip().lower().replace("ё", "е") for k in m.group(1).split("|") if k.strip()]
            if any(re.search(r"(?:^|[^а-яa-z])" + re.escape(k), low) for k in keys):
                words.append("• %s — %s" % (keys[0], m.group(2)))
    except Exception:
        pass
    if words:
        parts.append("СЛОВА ПОЛЬЗОВАТЕЛЯ в этом сообщении (~/.claude/workspace/WORDS.md):\n" + "\n".join(words[:4]))

emit(parts)
PY
exit 0
